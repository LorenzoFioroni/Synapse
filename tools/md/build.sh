#!/bin/sh
# Rebuilds frontend/vendor/md/ and frontend/vendor/mermaid/ from the pinned versions in package-lock.json.
# Usage: cd tools/md && npm ci && ./build.sh
set -e
V=../../frontend/vendor
rm -rf "$V/md" "$V/mermaid" && mkdir -p "$V/md/katex" "$V/mermaid"
npx esbuild entry.js --bundle --format=esm --minify --target=es2020 --outfile="$V/md/md.js" --legal-comments=none
cp node_modules/katex/dist/katex.min.css "$V/md/katex/"
cp -r node_modules/katex/dist/fonts "$V/md/katex/fonts"
rm -f "$V/md/katex/fonts/"*.ttf "$V/md/katex/fonts/"*.woff        # woff2 is enough for current browsers
cp node_modules/mermaid/dist/mermaid.min.js "$V/mermaid/"
cp node_modules/mermaid/LICENSE "$V/mermaid/LICENSE"
# licence list from what esbuild actually bundled
npx esbuild entry.js --bundle --format=esm --metafile=meta.json --outfile=/dev/null --log-level=error
node -e '
const fs=require("fs"); const meta=JSON.parse(fs.readFileSync("meta.json"));
const pk=new Set(Object.keys(meta.inputs).map((f)=>{const m=f.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/); return m&&m[1];}).filter(Boolean));
let out="Licences of the packages bundled into md.js (generated by tools/md).\n\n";
for (const n of [...pk].sort()) { const j=JSON.parse(fs.readFileSync(`node_modules/${n}/package.json`)); out+=`${n}@${j.version}  ${j.license}\n`; }
out+="\nmermaid.min.js: mermaid@"+JSON.parse(fs.readFileSync("node_modules/mermaid/package.json")).version+"  MIT (see ../mermaid/LICENSE)\n";
fs.writeFileSync(process.argv[1], out);' "$V/md/LICENSES.txt"
rm -f meta.json
echo "built: $(du -sh "$V/md" | cut -f1) md, $(du -sh "$V/mermaid" | cut -f1) mermaid"
