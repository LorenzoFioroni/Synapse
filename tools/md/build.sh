#!/bin/sh
# Rebuilds frontend/vendor/md/ and frontend/vendor/mermaid/ from the pinned versions in package-lock.json.
# Usage: cd tools/md && npm ci && ./build.sh
set -e
V=../../frontend/vendor
rm -rf "$V/md" "$V/mermaid" && mkdir -p "$V/md/katex" "$V/mermaid"
npx esbuild entry.js --bundle --format=esm --minify --target=es2020 --outfile="$V/md/md.js" --legal-comments=none
cp node_modules/katex/dist/katex.min.css "$V/md/katex/"
# types for TypeScript (frontend/src); frontend/package.json pins the same versions
cat > "$V/md/md.d.ts" <<'EOF'
// Types of md.js (tools/md/entry.js; written by tools/md/build.sh). The types come from katex and
// @types/markdown-it, installed in frontend/ for type checking at the same versions.
import type { PluginSimple } from 'markdown-it';

export { default as MarkdownIt } from 'markdown-it';
export { default as katex } from 'katex';
export declare const footnote: PluginSimple;
EOF
cp -r node_modules/katex/dist/fonts "$V/md/katex/fonts"
rm -f "$V/md/katex/fonts/"*.ttf "$V/md/katex/fonts/"*.woff        # woff2 is enough for current browsers
# Mermaid bundled here (mermaid-entry.js) from the locked dependencies, not Mermaid's prebuilt
# mermaid.min.js, which carries its own older copies of them (DOMPurify among them).
npx esbuild mermaid-entry.js --bundle --format=iife --minify --target=es2020 --outfile="$V/mermaid/mermaid.min.js" --legal-comments=none --log-level=warning
cp node_modules/mermaid/LICENSE "$V/mermaid/LICENSE"
# licence lists from what esbuild actually bundled
licences() {   # entry, format, title, output
  npx esbuild "$1" --bundle --format="$2" --metafile=meta.json --outfile=/dev/null --log-level=error
  node -e '
const fs=require("fs"); const meta=JSON.parse(fs.readFileSync("meta.json"));
const pk=new Set(Object.keys(meta.inputs).map((f)=>{const m=f.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/); return m&&m[1];}).filter(Boolean));
let out="Licences of the packages bundled into "+process.argv[1]+" (generated by tools/md).\n\n";
for (const n of [...pk].sort()) { const j=JSON.parse(fs.readFileSync(`node_modules/${n}/package.json`)); const lic=j.license || fs.readdirSync(`node_modules/${n}`).filter((f)=>/^licen[cs]e/i.test(f)).map((f)=>fs.readFileSync(`node_modules/${n}/${f}`,"utf8").split("\n")[0].trim())[0] || "unknown"; out+=`${n}@${j.version}  ${lic}\n`; }
fs.writeFileSync(process.argv[2], out);' "$3" "$4"
  rm -f meta.json
}
licences entry.js esm md.js "$V/md/LICENSES.txt"
licences mermaid-entry.js iife mermaid.min.js "$V/mermaid/LICENSES.txt"
echo "built: $(du -sh "$V/md" | cut -f1) md, $(du -sh "$V/mermaid" | cut -f1) mermaid"
