"""Generate Codex/Claude adapters from shared roles; --check detects drift without writing."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = "Generated by tools/agents.py; edit .agents/config.json or .agents/roles/*.md."


def adapters(root: Path) -> dict[Path, str]:
    config = json.loads((root / ".agents/config.json").read_text())
    if config["schema_version"] != 1:
        raise ValueError("Unsupported agent configuration version")
    output = {}
    names = set()
    for role in config["roles"]:
        name = role["name"]
        if not re.fullmatch(r"[a-z][a-z0-9-]*", name) or name in names:
            raise ValueError(f"Invalid or duplicate role name: {name}")
        names.add(name)
        profile = config["profiles"][role["profile"]]
        instructions = "Follow AGENTS.md.\n\n" + (root / f".agents/roles/{name}.md").read_text()
        codex = profile["codex"]
        fields = {"name": name, "description": role["description"], "model": codex["model"]}
        if "effort" in codex:
            fields["model_reasoning_effort"] = codex["effort"]
        fields["developer_instructions"] = instructions
        output[Path(f".codex/agents/{name}.toml")] = f"# {MARKER}\n" + "".join(
            f"{key} = {json.dumps(value)}\n" for key, value in fields.items()
        )
        claude = profile["claude"]
        fields = {"name": name, "description": role["description"], "model": claude["model"]}
        if "effort" in claude:
            fields["effort"] = claude["effort"]
        output[Path(f".claude/agents/{name}.md")] = (
            "---\n"
            + "".join(f"{key}: {json.dumps(value)}\n" for key, value in fields.items())
            + f"---\n\n<!-- {MARKER} -->\n\n{instructions}"
        )
    if config["default"] not in names:
        raise ValueError("The default agent must name a defined role")
    settings_path = root / ".claude/settings.json"
    settings = json.loads(settings_path.read_text()) if settings_path.exists() else {}
    settings["agent"] = config["default"]
    output[Path(".claude/settings.json")] = json.dumps(settings, indent=2) + "\n"
    return output


def sync(root: Path, *, check: bool) -> int:
    expected = adapters(root)
    stale = []
    for folder, pattern in ((".codex/agents", "*.toml"), (".claude/agents", "*.md")):
        for path in (root / folder).glob(pattern):
            if MARKER in path.read_text() and path.relative_to(root) not in expected:
                stale.append(path)
    changed = [
        path for path, text in expected.items() if not (root / path).exists() or (root / path).read_text() != text
    ]
    if check:
        for path in changed:
            print(f"Outdated agent adapter: {path}")
        for path in stale:
            print(f"Obsolete agent adapter: {path.relative_to(root)}")
        return int(bool(changed or stale))
    for path in stale:
        path.unlink()
    for path in changed:
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected[path])
    print(f"Generated {len(changed)} adapters; removed {len(stale)} obsolete adapters.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report drift without modifying files")
    args = parser.parse_args()
    return sync(ROOT, check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
